inline const TCHAR* MontageForFamily(EGolferAnimationFamily Family)
{
    switch (Family)
    {
        case EGolferAnimationFamily::Approach: return ApproachMontage;
        case EGolferAnimationFamily::Putt: return PuttMontage;
        default: return DriveMontage;
    }
}

/**
 * Fail-closed parity check between authoritative gameplay context and the
 * independently maintained presentation family. Drive context may select the
 * distance-dependent Drive or Approach family; putting contexts may select
 * only Putt. A stale or invalid presentation value must use synchronous
 * gameplay fallback instead of starting the wrong montage.
 */
inline bool IsFamilyCompatibleWithShotContext(
    EDiscShotContext ShotContext,
    EGolferAnimationFamily Family)
{
    switch (ShotContext)
    {
        case EDiscShotContext::Drive:
            return Family == EGolferAnimationFamily::Drive
                || Family == EGolferAnimationFamily::Approach;
        case EDiscShotContext::Circle1Putt:
        case EDiscShotContext::Circle2Putt:
            return Family == EGolferAnimationFamily::Putt;
        default:
            return false;
    }
}
